import * as Print from 'expo-print';

import { importFile } from '@/lib/documents';
import type { Doc } from '@/types/models';

/** Letter-size invoice HTML. Pure so the layout can be tested; expo-print turns it into the PDF. */
export function sampleInvoiceHtml(company: string, job: string, date: Date = new Date()): string {
  const d = date.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });
  const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c] ?? c);
  const rows = [
    ['Tear-off and disposal, 24 sq', '1', '1,850.00'],
    ['Architectural shingles, installed', '24', '4,320.00'],
    ['Ice and water shield, eaves and valleys', '1', '640.00'],
    ['Ridge vent and flashing', '1', '390.00'],
  ];
  const total = '7,200.00';
  return `<!doctype html><html><head><meta charset="utf-8"><style>
  @page{size:612pt 792pt;margin:0}body{margin:0;font-family:-apple-system,Helvetica,Arial,sans-serif;color:#15161A}
  .page{width:612pt;height:792pt;box-sizing:border-box;padding:48pt 48pt}
  h1{font-size:28pt;margin:0 0 4pt;letter-spacing:.5pt}.mono{font-family:Menlo,monospace;font-size:9pt;color:#5B5E66;letter-spacing:.3pt}
  .row{display:flex;justify-content:space-between;margin-top:18pt}.box{border:1px solid #C9C7C0;border-radius:4pt;padding:10pt 12pt}
  table{width:100%;border-collapse:collapse;margin-top:22pt;font-size:11pt}th{text-align:left;font-size:9pt;color:#5B5E66;letter-spacing:.4pt;border-bottom:1px solid #15161A;padding:6pt 0}
  td{padding:9pt 0;border-bottom:1px solid #C9C7C0}td.r,th.r{text-align:right}.total td{border-bottom:0;font-weight:700;font-size:13pt;padding-top:14pt}
  .sig{margin-top:56pt;display:flex;gap:28pt}.sig div{flex:1}.line{border-bottom:1px solid #15161A;height:28pt}.lbl{font-size:9pt;color:#5B5E66;margin-top:4pt}
  .foot{position:absolute;left:48pt;right:48pt;bottom:40pt;font-size:9pt;color:#5B5E66}
  </style></head><body><div class="page">
  <div class="mono">INVOICE · 0412 · ${esc(d.toUpperCase())}</div>
  <h1>${esc(company)}</h1>
  <div class="mono">JOB · ${esc(job.toUpperCase())}</div>
  <div class="row"><div class="box" style="flex:1;margin-right:12pt"><div class="mono">BILL TO</div><div style="font-size:12pt;margin-top:4pt">Client name<br/>Client address</div></div>
  <div class="box" style="flex:1"><div class="mono">TERMS</div><div style="font-size:12pt;margin-top:4pt">Due in 14 days<br/>Check, card or transfer</div></div></div>
  <table><tr><th>DESCRIPTION</th><th class="r">QTY</th><th class="r">AMOUNT</th></tr>
  ${rows.map(([n, q, a]) => `<tr><td>${esc(n)}</td><td class="r">${q}</td><td class="r">$${a}</td></tr>`).join('')}
  <tr class="total"><td>Total due</td><td></td><td class="r">$${total}</td></tr></table>
  <div class="sig"><div><div class="line"></div><div class="lbl">Contractor signature · date</div></div><div><div class="line"></div><div class="lbl">Client approval · date</div></div></div>
  <div class="foot">Sample invoice generated by Crew Lens. Replace it with your own PDF, or edit this one: tap Text, Check, Date or Sign, then Save and send.</div>
  </div></body></html>`;
}

/** Creates a sample invoice PDF for the job and files it as a document. Lets a new account try editing before uploading. */
export async function createSampleInvoice(jobId: string, company: string, job: string): Promise<Doc> {
  const out = await Print.printToFileAsync({ html: sampleInvoiceHtml(company, job), width: 612, height: 792, margins: { left: 0, top: 0, right: 0, bottom: 0 } });
  return importFile(jobId, { uri: out.uri, name: 'Sample invoice 0412', mimeType: 'application/pdf', size: null });
}
